export function getVisitById(id: string): Visit | undefined {
  return visits.find((visit) => visit.id === id)
}

export function getVisitsByDate(day: number, month: number, year: number): Visit[] {
  return visits.filter(
    (visit) =>
      visit.day === day && visit.month === month && visit.year === year
  )
}
